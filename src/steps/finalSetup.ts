import fs from "fs-extra";
import path from "path";
import {
  commandExists,
  run,
  getCommand,
  exitForInterrupt,
} from "../lib/process.js";
import {
  binaryCommand,
  productionReadmeCommands,
  runScriptCommand,
} from "../lib/packageManagerCommands.js";
import type { PackageManager } from "../lib/types.js";

const PM2_VERSION = "^5.4.2";

export function hasBun(): boolean {
  return commandExists("bun");
}

export function resolveRuntime(runtime: unknown): "node" | "bun" {
  if (runtime === "bun" && !hasBun()) {
    console.log("Bun was not found; using Node instead.");
    return "node";
  }
  if (runtime === "bun") return "bun";
  return "node";
}

export function createPm2Config(
  targetDir: string,
  projectName: string,
  runtime: "node" | "bun",
  productionEntry = "dist/server.js",
): void {
  const configPath = path.join(targetDir, "ecosystem.config.js");
  const useBun = runtime === "bun";

  const content = useBun
    ? `module.exports = {
  apps: [
    {
      name: "${projectName}",
      script: "${productionEntry}",
      interpreter: "bun",
      instances: "max",
      exec_mode: "cluster",
      watch: false,
      env: {
        NODE_ENV: "production"
      }
    }
  ]
}`
    : `module.exports = {
  apps: [
    {
      name: "${projectName}",
      script: "${productionEntry}",
      instances: "max",
      interpreter:"node",
      exec_mode: "cluster",
      watch: false,
      max_memory_restart: "300M",
      env: {
        NODE_ENV: "production"
      }
    }
  ]
};`;

  fs.writeFileSync(configPath, content, "utf-8");
}

export async function configureProduction(
  targetDir: string,
  projectName: string,
  runtime: "node" | "bun",
  packageManager: PackageManager = "npm",
): Promise<void> {
  const pkgPath = path.join(targetDir, "package.json");
  const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf-8"));

  pkg.dependencies["pm2"] = PM2_VERSION;

  delete pkg.dependencies["ts-node"];
  const productionEntry = String(pkg.scripts.start ?? "node dist/server.js")
    .replace(/^node\s+/, "")
    .trim();
  pkg.scripts["pm2:start"] = `${runScriptCommand(packageManager, "build")} && ${binaryCommand(packageManager, "pm2", "start ecosystem.config.js")}`;
  pkg.scripts["pm2:stop"] = binaryCommand(packageManager, "pm2", `stop ${projectName}`);
  pkg.scripts["pm2:logs"] = binaryCommand(packageManager, "pm2", "logs");

  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2));

  createPm2Config(targetDir, projectName, runtime, productionEntry);
}

export async function initGit(targetDir: string): Promise<boolean> {
  if (!commandExists("git")) return false;

  try {
    await run(getCommand("git"), ["init"], {
      cwd: targetDir,
      stdio: "ignore",
    });
    return true;
  } catch (error) {
    await exitForInterrupt(error);
    const message = error instanceof Error ? error.message.split("\n")[0] : String(error);
    console.warn(`Git initialization skipped: ${message}`);
    return false;
  }
}

export function appendProductionReadme(
  targetDir: string,
  projectName: string,
  packageManager: PackageManager = "npm",
): void {
  const readmePath = path.join(targetDir, "README.md");
  if (fs.readFileSync(readmePath, "utf8").includes("## Production Mode")) return;
  const commands = productionReadmeCommands(packageManager);
  fs.appendFileSync(
    readmePath,
    `

## Production Mode

This project is configured for production using PM2.

Build and start the compiled app in cluster mode:

${commands.start}

View logs:

${commands.logs}

Stop app:

${commands.stop}

   `,
  );
}

export type ProductionChecklistFeatures = {
  prisma: boolean;
  oauthProviders: readonly string[];
};

export function buildProductionChecklist(
  projectName: string,
  packageManager: PackageManager,
  features: ProductionChecklistFeatures,
): string {
  const providerName = (provider: string): string =>
    provider === "github" ? "GitHub" : provider === "google" ? "Google" : provider;

  const lines: string[] = [
    `# Production deployment checklist for ${projectName}`,
    "",
    "Generated by create-authenik8-app. Work through every section in order, then",
    "require the production Doctor gate to pass before serving real traffic. The",
    "Doctor diagnostics are the policy source of truth; this checklist never",
    "weakens them.",
    "",
    "## 1. Store secrets in a deployment secret manager",
    "",
    "Never commit or log these values; inject them as deployment environment",
    "variables. Never put them into authenik8.json or client-visible configuration.",
    "",
  ];
  lines.push(
    "- `AUTHENIK8_SIGNING_JWKS` — the ES256 signing key ring. Keep private JWK",
    "  fields out of the repository, the manifest, and logs.",
    "- `AUTHENIK8_ACTIVE_KID` — the signing key currently in use. Rotate with",
    "  `npx create-authenik8-app@latest ops rotate signing-key`, and deploy the",
    "  staged key ring to every instance before activating it.",
    "- `REFRESH_SECRET` — at least 32 random characters.",
  );
  for (const provider of features.oauthProviders) {
    const prefix = provider.toUpperCase();
    lines.push(
      `- \`${prefix}_CLIENT_ID\`, \`${prefix}_CLIENT_SECRET\`, and \`${prefix}_REDIRECT_URI\` — exact HTTPS callback URL registered with ${providerName(provider)}.`,
    );
  }

  lines.push(
    "",
    "## 2. Configure the production environment",
    "",
    "| Variable | Policy enforced by Doctor | Check |",
    "| --- | --- | --- |",
    "| `NODE_ENV` | Set to `production` | A8-PROD-001 |",
    "| `REDIS_URL` | Private external `redis://` or `rediss://` endpoint; `memory://` and loopback instances do not pass the gate | A8-PROD-002 |",
    "| `AUTHENIK8_ISSUER` | Exact non-local HTTPS URL | A8-PROD-003 |",
  );
  for (const provider of features.oauthProviders) {
    const prefix = provider.toUpperCase();
    lines.push(
      `| \`${prefix}_REDIRECT_URI\` | Exact HTTPS callback URL registered with ${providerName(provider)} | A8-PROD-003 |`,
    );
  }
  if (features.prisma) {
    lines.push(
      "| `DATABASE_URL` | Managed, backed-up PostgreSQL outside this machine | Runtime contract; fullstack projects are hard-gated by A8-PROD-005 |",
    );
  }

  lines.push(
    "",
    "## 3. Data services",
    "",
    "- Keep PostgreSQL and Redis on private networks with authentication and",
    "  encryption where supported.",
    "- Configure automated PostgreSQL backups and perform restore drills.",
  );
  if (features.prisma) {
    lines.push(
      "- Run Prisma migrations as a controlled release step (`npm run db:migrate`),",
      "  not concurrently from every replica.",
    );
  }

  lines.push(
    "",
    "## 4. Build and run",
    "",
    "Use the generated PM2 scripts `pm2:start`, `pm2:stop`, and `pm2:logs`; the",
    "Production section of README.md shows the exact commands, and the generated",
    "`ecosystem.config.js` already sets `NODE_ENV` to `production`.",
    "",
    "## 5. Gate the deployment",
    "",
    "```bash",
    "npx create-authenik8-app@latest ops readiness",
    "npx create-authenik8-app@latest doctor --production",
    "```",
    "",
    "A failing production diagnostic is a deploy blocker: fix it and re-run until",
    "the gate passes, then keep an `ops audit production` receipt with your",
    "release evidence.",
    "",
  );
  return lines.join("\n");
}

export function writeProductionChecklist(
  targetDir: string,
  projectName: string,
  packageManager: PackageManager,
  features: ProductionChecklistFeatures,
): void {
  const docsDir = path.join(targetDir, "docs");
  fs.mkdirSync(docsDir, { recursive: true });
  fs.writeFileSync(
    path.join(docsDir, "PRODUCTION.md"),
    buildProductionChecklist(projectName, packageManager, features),
    "utf-8",
  );
}
